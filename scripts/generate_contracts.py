class ContractVersionDefinition(BaseModel):
    """Version definition parsed from the canonical schema."""

    model_config: ClassVar[ConfigDict] = ConfigDict(frozen=True)

    const: str = Field(pattern=r"^[0-9]+\.[0-9]+\.[0-9]+$")


class ContractProperties(BaseModel):
    """Contract properties required by code generation."""

    model_config: ClassVar[ConfigDict] = ConfigDict(frozen=True)

    contract_version: ContractVersionDefinition


class ContractSchema(BaseModel):
    """Minimal typed view of the canonical JSON Schema."""

    model_config: ClassVar[ConfigDict] = ConfigDict(frozen=True)

    properties: ContractProperties


class ConversationSchema(BaseModel):
    """Typed view of the canonical conversation JSON Schema."""

    model_config: ClassVar[ConfigDict] = ConfigDict(frozen=True)

    properties: ContractProperties
    defs: dict[str, object] = Field(alias="$defs")


def generated_sources(version: str) -> tuple[str, str]:
    """Render deterministic Python and Swift version sources."""
    python_source = (
        '"""Generated contract version; update through the canonical schema."""\n\n'
        "# Generated by scripts/generate_contracts.py; do not edit.\n"
        "from typing import Final\n\n"
        f'CONTRACT_VERSION: Final = "{version}"\n'
    )
    swift_source = (
        "// Generated by scripts/generate_contracts.py; do not edit.\n"
        "public struct SecretaryContractVersion: Equatable, Sendable {\n"
        "    public static let current = SecretaryContractVersion()\n"
        f'    public let rawValue = "{version}"\n\n'
        "    private init() {}\n"
        "}\n"
    )
    return python_source, swift_source


def conversation_sources(version: str) -> tuple[str, str]:
    """Render deterministic Python and Swift conversation API sources."""
    return (
        _CONVERSATION_PYTHON_TEMPLATE.replace("__VERSION__", version),
        _CONVERSATION_SWIFT_TEMPLATE.replace("__VERSION__", version),
    )


def update_source(path: Path, content: str, *, check: bool) -> bool:
    """Write one generated source or report whether it is current."""
    if check:
        return path.is_file() and path.read_text(encoding="utf-8") == content
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def main() -> int:
    """Generate both language bindings from the canonical schemas."""
    unexpected_arguments = set(sys.argv[1:]) - {"--check"}
    if unexpected_arguments:
        sys.stderr.write(f"unexpected arguments: {sorted(unexpected_arguments)}\n")
        return 2

    schema = ContractSchema.model_validate_json(SCHEMA_PATH.read_bytes())
    conversation_schema = ConversationSchema.model_validate_json(
        CONVERSATION_SCHEMA_PATH.read_bytes()
    )
    if set(conversation_schema.defs) != CONVERSATION_DEFS:
        sys.stderr.write("conversation schema defs drifted from the generated bindings\n")
        return 2

    version = schema.properties.contract_version.const
    conversation_version = conversation_schema.properties.contract_version.const
    if conversation_version != version:
        sys.stderr.write("conversation schema version drifted from the transport schema\n")
        return 2

    python_source, swift_source = generated_sources(version)
    conversation_python, conversation_swift = conversation_sources(conversation_version)
    check = "--check" in sys.argv[1:]
    current = all(
        (
            update_source(PYTHON_PATH, python_source, check=check),
            update_source(SWIFT_PATH, swift_source, check=check),
            update_source(CONVERSATION_PYTHON_PATH, conversation_python, check=check),
            update_source(CONVERSATION_SWIFT_PATH, conversation_swift, check=check),
        )
    )
    if check and not current:
        sys.stderr.write("generated contract sources are stale\n")
        return 1
    return 0


