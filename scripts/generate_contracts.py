class ConversationJournal:
    """Ordering gate for a single conversation's event stream."""

    def __init__(self, conversation: Conversation, devices: list[ConversationDevice]) -> None:
        """Bind the journal to one conversation and its enrolled devices."""
        self._conversation: Conversation = conversation
        self._devices: dict[UUID, ConversationDevice] = {
            device.device_id: device for device in devices
        }
        self._next_sequence: int = 1
        self._seen_event_ids: set[UUID] = set()
        self._open_turn_id: UUID | None = None
        self._cancelled_turn_id: UUID | None = None

    def accept(self, event: ConversationEvent) -> ConversationAcceptance:
        """Accept one ordered event or reject it with a typed reason."""
        rejection = self._envelope_rejection(event)
        if rejection is not None:
            return self._reject(rejection)
        rejection = self._payload_rejection(event)
        if rejection is not None:
            return self._reject(rejection)
        self._seen_event_ids.add(event.event_id)
        self._next_sequence += 1
        self._apply_payload_state(event)
        return ConversationAcceptance(
            accepted=True, rejection=None, next_sequence=self._next_sequence
        )

    def _reject(self, rejection: ConversationRejection) -> ConversationAcceptance:
        return ConversationAcceptance(
            accepted=False,
            rejection=rejection,
            next_sequence=self._next_sequence,
        )

    def _envelope_rejection(self, event: ConversationEvent) -> ConversationRejection | None:
        if event.conversation_id != self._conversation.conversation_id:
            return ConversationRejection.UNKNOWN_CONVERSATION
        if self._conversation.state != ConversationState.ACTIVE:
            return ConversationRejection.CONVERSATION_CLOSED
        if event.event_id in self._seen_event_ids:
            return ConversationRejection.DUPLICATE_EVENT
        if event.participant_id not in self._conversation.participant_ids:
            return ConversationRejection.FOREIGN_PARTICIPANT
        device = self._devices.get(event.device_id)
        if device is None or event.device_id not in self._conversation.device_ids:
            return ConversationRejection.FOREIGN_DEVICE
        if device.participant_id != event.participant_id:
            return ConversationRejection.DEVICE_PARTICIPANT_MISMATCH
        if event.kind.value != event.payload.kind:
            return ConversationRejection.KIND_MISMATCH
        if event.sequence != self._next_sequence:
            return ConversationRejection.OUT_OF_ORDER
        return None

    def _payload_rejection(self, event: ConversationEvent) -> ConversationRejection | None:
        payload = event.payload
        if isinstance(payload, TranscriptPartial | TranscriptFinal):
            if self._cancelled_turn_id is not None and payload.turn_id == self._cancelled_turn_id:
                return ConversationRejection.EVENT_AFTER_CANCELLATION
            if self._open_turn_id is None:
                if isinstance(payload, TranscriptFinal):
                    return ConversationRejection.FINAL_WITHOUT_PARTIAL
            elif payload.turn_id != self._open_turn_id:
                return ConversationRejection.TURN_CLOSED
        elif isinstance(payload, Resume):
            if (
                self._cancelled_turn_id is None
                or payload.resume_from_turn_id != self._cancelled_turn_id
            ):
                return ConversationRejection.RESUME_WITHOUT_CANCELLATION
        return None

    def _apply_payload_state(self, event: ConversationEvent) -> None:
        payload = event.payload
        if isinstance(payload, TranscriptPartial):
            self._open_turn_id = payload.turn_id
        elif isinstance(payload, TranscriptFinal):
            self._open_turn_id = None
        elif isinstance(payload, Cancellation):
            self._open_turn_id = None
            self._cancelled_turn_id = payload.turn_id
        elif isinstance(payload, Resume):
            self._open_turn_id = payload.turn_id
            self._cancelled_turn_id = None
